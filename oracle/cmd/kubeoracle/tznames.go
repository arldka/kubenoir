package main

import (
	"archive/zip"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

// tznames writes the IANA time zone names Go's time.LoadLocation knows (from the Go
// distribution's lib/time/zoneinfo.zip), for CronJob `timeZone` validation in the engine.
func tznames(out string) error {
	r, err := zip.OpenReader(filepath.Join(runtime.GOROOT(), "lib", "time", "zoneinfo.zip"))
	if err != nil {
		return err
	}
	defer r.Close()
	var names []string
	for _, f := range r.File {
		if !strings.HasSuffix(f.Name, "/") {
			names = append(names, f.Name)
		}
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("// @generated by `kubeoracle tznames` (make oracle-goldens) from Go's zoneinfo.zip.\n")
	b.WriteString("// Do not edit. The time zones Go's `time.LoadLocation` knows.\n\n")
	b.WriteString("/// Whether `time.LoadLocation(name)` succeeds (`UTC` and the names below).\n")
	b.WriteString("pub fn is_known(name: &str) -> bool {\n")
	b.WriteString("    name == \"UTC\" || NAMES.binary_search(&name).is_ok()\n")
	b.WriteString("}\n\n")
	b.WriteString("#[rustfmt::skip]\n")
	b.WriteString("static NAMES: &[&str] = &[\n")
	for _, n := range names {
		fmt.Fprintf(&b, "    %q,\n", n)
	}
	b.WriteString("];\n")
	return os.WriteFile(out, []byte(b.String()), 0o644)
}
